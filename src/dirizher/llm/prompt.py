def build_summary_prompt(transcript_text: str) -> str:
    return (
        "Транскрипт встречи (размечен по говорящим, старые → новые реплики):\n"
        f'"""\n{transcript_text.strip()}\n"""\n\n'
        "Сделай саммари строго по заданному формату."
    )


# Доп. инструкция для извлечения задач из встречи. На встрече каждая ЯВНАЯ
# договорённость = задача, даже если действие кажется бытовым/необычным, — иначе
# теряем поручения вроде «Валера — съесть арбузы к понедельнику». Анти-галлюцинация
# при этом сохраняется: придумывать ничего нельзя, исполнитель должен быть назван.
_MEETING_NOTE = """\
ВАЖНО (источник = встреча): это транскрипт рабочей встречи. Оформляй задачей
КАЖДУЮ явную договорённость — конкретное действие с НАЗВАННЫМ исполнителем —
ДАЖЕ если действие выглядит бытовым/необычным. Правило про игнор личных/бытовых
планов на встрече НЕ применяется к явно зафиксированным поручениям («договорились,
что X сделает Y к сроку»). НЕ выдумывай того, чего в транскрипте не было, и НЕ
дроби одну договорённость на несколько карточек.
"""


def build_user_prompt(message: str, ctx: ExtractionContext) -> str:
    team = ", ".join(ctx.team_names()) or "(команда не задана)"
    memory = ctx.memory_context.strip() or "(нет дополнительного контекста)"
    dialog = "\n".join(ctx.recent_dialog) or "(переписки нет)"
    meeting_note = f"{_MEETING_NOTE}\n" if "встреч" in ctx.source_label.lower() else ""
    return (
        f"today = {ctx.today.isoformat()} ({_RU_WEEKDAYS[ctx.today.weekday()]})\n"
        f"справочник_дат (используй готовые даты, НЕ считай сам):\n{_date_reference(ctx.today)}\n"
        f"источник = {ctx.source_label}\n"
        f"команда = {team}\n"
        f"{meeting_note}"
        f"контекст_из_памяти:\n{memory}\n\n"
        f"НЕДАВНЯЯ ПЕРЕПИСКА (контекст, старые → новые):\n{dialog}\n\n"
        f"ПОСЛЕДНЕЕ СООБЩЕНИЕ (его и анализируем):\n\"\"\"\n{message}\n\"\"\"\n\n"
        f"Верни JSON со списком задач."
    )
