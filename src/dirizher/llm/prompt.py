"""Промпт и схема для извлечения задач боевыми LLM (Groq / GigaChat)."""

from __future__ import annotations

from datetime import date, timedelta

from .base import ExtractionContext

_RU_WEEKDAYS = [
    "понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье",
]


def _date_reference(today: date) -> str:
    """Готовый справочник дат с днями недели — чтобы LLM не считал сам.

    Модели регулярно ошибаются на ±1 день при вычислении «следующий понедельник».
    Поэтому даём явную таблицу: ближайшая будущая дата каждого дня недели + завтра.
    """
    lines = [f"  сегодня = {today.isoformat()} ({_RU_WEEKDAYS[today.weekday()]})"]
    lines.append(f"  завтра = {(today + timedelta(days=1)).isoformat()}")
    lines.append(f"  послезавтра = {(today + timedelta(days=2)).isoformat()}")
    # Ближайшее будущее вхождение каждого дня недели (delta 1..7).
    for idx, name in enumerate(_RU_WEEKDAYS):
        delta = (idx - today.weekday()) % 7 or 7
        lines.append(f"  ближайший(-ая) {name} = {(today + timedelta(days=delta)).isoformat()}")
    lines.append(f"  через неделю = {(today + timedelta(days=7)).isoformat()}")
    return "\n".join(lines)

